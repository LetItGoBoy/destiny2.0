function analyze(ctx, t, strength, geJu, elemStatus) {
  var sections = [];

  // 1. 日主底色
  sections.push({
    title: '日主 ' + ctx.dayGan + t.dm,
    cls: base.WX_CLS[t.dm],
    text: DAY_GAN_TEXT[ctx.dayGan]
  });

  // 2. 主导十神（取加权前二，需有足够分量）
  var gods = [];
  var g;
  for (g in t.god) gods.push({ name: g, score: t.god[g] });
  gods.sort(function (a, b) { return b.score - a.score; });
  var threshold = t.total * 0.16;
  for (var i = 0; i < 2 && i < gods.length; i++) {
    if (gods[i].score < threshold) break;
    sections.push({
      title: '主星 ' + gods[i].name,
      cls: '',
      text: GOD_TRAITS[gods[i].name]
    });
  }

  // 3. 格局人格
  if (geJu && geJu.personality) {
    sections.push({
      title: '格局 ' + geJu.name,
      cls: '',
      text: geJu.personality
    });
  }

  // 4. 五行缺失补注
  var lacks = [];
  base.WX_LIST.forEach(function (w) {
    if (elemStatus && elemStatus[w] === '缺') lacks.push(LACK_TEXT[w]);
  });
  if (lacks.length) {
    sections.push({ title: '五行补注', cls: '', text: lacks.join('') });
  }

  return { sections: sections };
}

module.exports = { analyze: analyze };
