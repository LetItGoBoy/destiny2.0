/**
 * 查询词条，返回统一卡片结构 { name, brief, blocks: [{type, title, text}] }
 * type: xi(喜)/ji(忌)/plain(中性)
 */
function lookup(term) {
  if (!term) return null;
  if (shiShen[term]) {
    var s = shiShen[term];
    return {
      name: term,
      brief: s.brief,
      blocks: [
        { type: 'xi', title: '为喜用时', text: s.xi },
        { type: 'ji', title: '为忌时', text: s.ji }
      ]
    };
  }
  if (changSheng[term]) {
    var c = changSheng[term];
    return { name: term, brief: c.brief, blocks: [{ type: 'plain', title: '', text: c.text }] };
  }
  if (shenSha[term]) {
    var ss = shenSha[term];
    return { name: term, brief: ss.brief, blocks: [{ type: 'plain', title: '', text: ss.text }] };
  }
  if (naYin[term]) {
    return {
      name: term,
      brief: '纳音五行 · ' + term.charAt(term.length - 1),
      blocks: [{ type: 'plain', title: '', text: naYin[term] }]
    };
  }
  return null;
}

